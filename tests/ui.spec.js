test('Firebase signup, reader restriction, logout, and login errors work', async ({ page, request }) => {
  const email = `browser-${Date.now()}@example.test`;
  await page.goto('/signup');
  await page.getByRole('textbox', { name: 'Your name' }).fill('Browser Reader');
  await page.getByRole('textbox', { name: 'Email address' }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('StrongPassword123!');
  await page.getByLabel('Confirm password', { exact: true }).fill('DifferentPassword123!');
  await page.getByRole('button', { name: 'Create account', exact: true }).last().click();
  await expect(page.getByRole('alert')).toContainText('Your passwords do not match.');
  await page.getByLabel('Confirm password', { exact: true }).fill('StrongPassword123!');
  await page.getByRole('button', { name: 'Create account', exact: true }).last().click();
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
  await page.goto('/admin');
  await expect(page.getByRole('heading', { name: 'Admin access required' })).toBeVisible();
  const token = await page.evaluate(async () => { const { auth } = await import('/src/config/firebase.js'); return auth.currentUser.getIdToken(); });
  const response = await request.post('/api/admin/posts', { headers: { Authorization: `Bearer ${token}` }, data: { title: 'Unauthorized post' } });
  expect(response.status()).toBe(403);
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible();
  await page.goto('/login');
  await page.getByRole('textbox', { name: 'Email address' }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('WrongPassword123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).last().click();
  await expect(page.getByRole('alert')).toContainText('The email or password is incorrect.');
  await page.getByLabel('Password', { exact: true }).fill('StrongPassword123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).last().click();
  await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
});

test('admin can create, preview, publish, view, edit, and delete a blog post', async ({ page, request }) => {
  const title = `A browser-tested note ${Date.now()}`;
  await page.goto('/login');
  await page.getByRole('textbox', { name: 'Email address' }).fill('admin@fieldnotes.local');
  await page.getByLabel('Password', { exact: true }).fill('Fieldnotes123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).last().click();
  await expect(page.getByRole('link', { name: 'Admin panel', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Admin panel', exact: true }).click();
  await page.getByRole('link', { name: 'Create post' }).click();
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(title);
  await page.getByRole('textbox', { name: 'Excerpt' }).fill('A real end-to-end test of the full publishing workflow.');
  await page.getByRole('textbox', { name: 'Content', exact: true }).fill('## A useful discovery\n\nThis article was written and saved through the browser, authenticated by Firebase, and persisted to MongoDB.');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.locator('.markdown-preview')).toContainText('A useful discovery');
  await page.getByRole('button', { name: 'Save draft' }).click();
  await expect(page.getByRole('heading', { name: 'Admin dashboard' })).toBeVisible();
  const row = page.locator('.admin-row').filter({ hasText: title });
  await expect(row).toContainText('draft');
  const feed = await request.get('/api/posts');
  expect((await feed.json()).posts.some(post => post.title === title)).toBe(false);
  await row.getByRole('link', { name: `Edit ${title}`, exact: true }).click();
  await page.getByLabel('Publish status').selectOption('published');
  await page.getByRole('button', { name: 'Save & publish' }).click();
  await expect(row).toContainText('published');
  await row.getByRole('link', { name: `View ${title}`, exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  await expect(page.locator('.article-prose')).toContainText('persisted to MongoDB');
  const articlePath = new URL(page.url()).pathname;
  await page.goto('/admin');
  await page.locator('.admin-row').filter({ hasText: title }).getByRole('link', { name: `Edit ${title}`, exact: true }).click();
  await page.getByRole('textbox', { name: 'Excerpt' }).fill('An updated introduction, saved after the first publication.');
  await page.getByRole('button', { name: 'Save & publish' }).click();
  await expect(page.getByRole('heading', { name: 'Admin dashboard' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/admin-desktop.png', fullPage: true });
  await page.locator('.admin-row').filter({ hasText: title }).getByRole('button', { name: `Delete ${title}`, exact: true }).click();
  await page.getByRole('button', { name: 'Cancel' }).click();
  await expect(page.locator('.admin-row').filter({ hasText: title })).toBeVisible();
  await page.locator('.admin-row').filter({ hasText: title }).getByRole('button', { name: `Delete ${title}`, exact: true }).click();
  await page.getByRole('button', { name: 'Delete post', exact: true }).click();
  await expect(page.locator('.admin-row').filter({ hasText: title })).toHaveCount(0);
  await page.goto(articlePath);
  await expect(page.getByText('This article could not be found.')).toBeVisible();
});
