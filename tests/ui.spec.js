import { test, expect } from '@playwright/test';

test('journal loads, searches, filters, and opens a full article', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /MERN Stack Developer/ })).toBeVisible();
  await expect(page.locator('.featured-post')).toBeVisible();
  await page.screenshot({ path: 'artifacts/journal-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Design', exact: true }).click();
  await expect(page.locator('.post-card')).toHaveCount(1);
  await expect(page.locator('.post-card')).toContainText('Making space for the important things.');
  await page.getByRole('button', { name: 'All posts', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search articles' }).fill('no matching article exists');
  await expect(page.getByRole('heading', { name: 'No articles found.' })).toBeVisible();
  await page.getByRole('button', { name: 'View all articles' }).click();
  await expect(page.locator('.featured-post')).toBeVisible();
  await page.locator('.featured-post').click();
  await expect(page.locator('.article-prose')).toContainText('Start with the smallest useful thing');
  expect(errors).toEqual([]);
});

